import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Rewrites KaTeX's stylesheet so every font is a data URI. Expo's Metro CSS
// pipeline does not resolve url() assets, and the web UI is served from
// several base paths (Expo dev, Cloudflare, the daemon, paseo://app/), so a
// relative font URL would break on at least one of them. Only woff2 is kept:
// every supported browser and Electron read it.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../../../../..");
const require = createRequire(import.meta.url);
const katexCssPath = require.resolve("katex/dist/katex.min.css");
const fontsDir = path.join(path.dirname(katexCssPath), "fonts");
const output = path.join(__dirname, "katex-css.gen.ts");

const FONT_SRC_RE =
  /src:url\(fonts\/([A-Za-z0-9_-]+)\.woff2\) format\("woff2"\)(?:,url\(fonts\/[A-Za-z0-9_-]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\))*/g;

const css = await fs.readFile(katexCssPath, "utf8");
let fontCount = 0;
const inlined = await replaceAsync(css, FONT_SRC_RE, async (_match, fontName) => {
  const bytes = await fs.readFile(path.join(fontsDir, `${fontName}.woff2`));
  fontCount += 1;
  return `src:url(data:font/woff2;base64,${bytes.toString("base64")}) format("woff2")`;
});

if (fontCount === 0 || inlined.includes("url(fonts/")) {
  throw new Error("KaTeX stylesheet format changed; update FONT_SRC_RE in build-katex-css.mjs");
}

const contents = `// Generated by packages/app/src/components/markdown/math/build-katex-css.mjs.
// Do not edit by hand. Regenerate with \`npm run build:katex-css --workspace=@getpaseo/app\`.

export const katexCss = ${JSON.stringify(inlined)};
`;

await fs.writeFile(output, contents);
console.log(
  `Wrote ${path.relative(repoRoot, output)} (${inlined.length} bytes, ${fontCount} fonts inlined)`,
);

async function replaceAsync(input, pattern, replacer) {
  const replacements = [];
  input.replace(pattern, (match, ...args) => {
    replacements.push(replacer(match, ...args));
    return match;
  });
  const resolved = await Promise.all(replacements);
  let index = 0;
  return input.replace(pattern, () => resolved[index++]);
}
